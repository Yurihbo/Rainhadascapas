import fs from 'node:fs';
const path = 'client/src/pages/Home.tsx';
let source = fs.readFileSync(path, 'utf8');
const oldBlock = `    const printWindow = window.open("", "_blank", "noopener,noreferrer,width=900,height=700");
    if (!printWindow) { toast.error("Permita a abertura de janelas para imprimir a lista"); return; }`;
const newBlock = `    const printWindow = window.open("", "_blank", "width=900,height=700");
    if (!printWindow) { toast.error("Permita janelas pop-up para imprimir a lista"); return; }`;
if (!source.includes(oldBlock)) throw new Error('print window block not found');
source = source.replace(oldBlock, newBlock);
const oldEnd = `    printWindow.document.write(html);
    printWindow.document.close();`;
const newEnd = `    let hasPrinted = false;
    const printReadyDocument = () => {
      if (hasPrinted || printWindow.closed) return;
      hasPrinted = true;
      printWindow.focus();
      printWindow.print();
    };
    printWindow.onafterprint = () => setTimeout(() => printWindow.close(), 300);
    printWindow.document.open();
    printWindow.document.write(html);
    printWindow.document.close();
    printWindow.addEventListener("load", () => setTimeout(printReadyDocument, 250), { once: true });
    setTimeout(printReadyDocument, 1200);`;
if (!source.includes(oldEnd)) throw new Error('print document block not found');
source = source.replace(oldEnd, newEnd);
fs.writeFileSync(path, source);
console.log('White merchandise print flow fixed.');
